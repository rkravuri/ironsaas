#!/bin/sh
# Creates a locally trusted TLS certificate for the laptop hostnames with mkcert. Optional:
# without it Traefik serves https with its own self-signed certificate, and http works as before.
set -eu
here=$(cd "$(dirname "$0")/.." && pwd)

if ! command -v mkcert >/dev/null 2>&1; then
  echo "mkcert is not installed. On Ubuntu: sudo apt install -y mkcert libnss3-tools && mkcert -install"
  exit 1
fi

names="localhost traefik.localhost grafana.localhost prometheus.localhost tempo.localhost openbao.localhost control.localhost"
for tenant in "$@"; do
  names="$names $tenant.localhost"
done

mkdir -p "$here/certs"
# shellcheck disable=SC2086
mkcert -cert-file "$here/certs/local.crt" -key-file "$here/certs/local.key" $names 127.0.0.1 ::1

cat > "$here/traefik/dynamic/tls.yaml" <<YAML
# Generated by infra/compose/scripts/make-certs.sh. Ignored by git. Traefik reloads this folder on change.
tls:
  certificates:
    - certFile: /certs/local.crt
      keyFile: /certs/local.key
YAML

caroot=$(mkcert -CAROOT)
cat <<TEXT

Certificate written to infra/compose/certs/ for: $names
Traefik picks it up without a restart.

Browsers run on Windows, so the mkcert root certificate must be trusted there as well:
  1. Copy $caroot/rootCA.pem to Windows, for example to your Desktop.
  2. In an administrator PowerShell: certutil -addstore -f ROOT rootCA.pem
Then restart the browser and open https://grafana.localhost.
TEXT
