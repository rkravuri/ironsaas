using System.Text;
using System.Text.Json;

namespace Iron.Kernel.Api.Modules;

/// <summary>
/// The shell's typed setting keys (ADR-0036): a TypeScript file with every setting the shell may see, its value type and
/// its default, written by <c>make catalogue</c> beside the catalogue and held to the code by the same host test, so
/// <c>useSetting</c> takes only a declared key and answers its type.
/// </summary>
public static class ShellSettingKeys
{
    /// <summary>Where the file lives, from the repository root.</summary>
    public const string RelativePath = "shell/src/api/setting-keys.ts";

    public static string ToTypeScript(LicensingCatalogue catalogue)
    {
        ArgumentNullException.ThrowIfNull(catalogue);
        var visible = catalogue.Settings.Where(s => s.VisibleToShell && s.Type != SettingType.SecretReference).ToList();
        var text = new StringBuilder();
        text.Append("// Generated by make catalogue from the settings the modules declare (ADR-0036). Do not edit: change the\n");
        text.Append("// declaration in its module and run make catalogue; the host test fails while this file and the code differ.\n");
        text.Append('\n');
        text.Append("/** The settings the shell may read, each with the type of its value. */\n");
        text.Append("export interface SettingValues {\n");
        foreach (var setting in visible)
        {
            text.Append("  ").Append(Quote(setting.Key)).Append(": ").Append(TypeOf(setting)).Append(";\n");
        }

        text.Append("}\n");
        text.Append('\n');
        text.Append("export type SettingKey = keyof SettingValues;\n");
        text.Append('\n');
        text.Append("/** The default in code of each: what the shell uses until /me/context answers, and when it cannot. */\n");
        text.Append("export const settingDefaults: SettingValues = {\n");
        foreach (var setting in visible)
        {
            text.Append("  ").Append(Quote(setting.Key)).Append(": ").Append(JsonSerializer.Serialize(setting.Default)).Append(",\n");
        }

        text.Append("};\n");
        return text.ToString();
    }

    private static string TypeOf(SettingEntry setting) => setting.Type switch
    {
        SettingType.Text => "string",
        SettingType.Number => "number",
        SettingType.Boolean => "boolean",
        SettingType.Choice => string.Join(" | ", (setting.Choices ?? []).Select(Quote)),
        _ => "unknown",
    };

    private static string Quote(string value) => JsonSerializer.Serialize(value);
}
