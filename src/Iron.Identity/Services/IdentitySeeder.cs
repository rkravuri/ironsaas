using Iron.Audit.Contracts;
using Iron.Authorization.Contracts;
using Iron.Data.Seeding;
using Iron.Data.Transactions;
using Iron.Identity.Contracts;
using Iron.Identity.Data;
using Microsoft.EntityFrameworkCore;
using Microsoft.Extensions.Logging;

namespace Iron.Identity.Services;

/// <summary>Bound from the <c>Seed:Administrator</c> section: the first administrator of a new tenant (S1 plan, provisioning step 4).</summary>
public sealed class AdministratorSeedOptions
{
    public const string SectionName = "Seed:Administrator";

    public string? LoginId { get; set; }

    public string? DisplayName { get; set; }
}

/// <summary>
/// One entry of the <c>Seed:ServiceAccounts</c> list: a service account the seed creates with a role. A tenant unit gets the
/// smoke client (service-default); the control plane gets the operator (tenant-administrator). The secret is generated by
/// the fleet per unit (T14) and handed to the seed once; only its Argon2id hash is stored.
/// </summary>
public sealed class ServiceAccountSeedOptions
{
    public const string SectionName = "Seed:ServiceAccounts";

    public string? ClientId { get; set; }

    public string? Secret { get; set; }

    public string Role { get; set; } = SystemRoles.ServiceDefault;

    public string? DisplayName { get; set; }
}

/// <summary>The bound list, registered as one service so the seeder can take it.</summary>
public sealed class ServiceAccountSeeds(IReadOnlyList<ServiceAccountSeedOptions> accounts)
{
    public IReadOnlyList<ServiceAccountSeedOptions> Accounts { get; } = accounts;
}

/// <summary>
/// Creates the first administrator in Invited status with an invitation token and the tenant-administrator role, and
/// the configured service accounts, Active, each with its role. Runs after the Authorization seeder (order 100).
/// Without the configuration, each part does nothing. The invitation token is written to the log once, at creation,
/// because no email leaves a unit in S1; the fleet prints the link (T14). Running again changes nothing, except that an
/// existing service account takes the secret the seed was given when it differs (ADR-0028).
/// </summary>
public sealed class IdentitySeeder(
    IdentityDbContext context,
    AdministratorSeedOptions options,
    ServiceAccountSeeds serviceAccounts,
    InvitationService invitations,
    IPasswordHasher hasher,
    IRoleAssignments roleAssignments,
    IUnitOfWork unitOfWork,
    IAuditWriter audit,
    ILogger<IdentitySeeder> logger) : ISeeder
{
    public int Order => 200;

    public async Task SeedAsync(CancellationToken cancellationToken)
    {
        await SeedAdministratorAsync(cancellationToken).ConfigureAwait(false);
        foreach (var account in serviceAccounts.Accounts)
        {
            await SeedServiceAccountAsync(account, cancellationToken).ConfigureAwait(false);
        }
    }

    private async Task SeedServiceAccountAsync(ServiceAccountSeedOptions account, CancellationToken cancellationToken)
    {
        var clientId = Principal.NormaliseLoginId(account.ClientId);
        if (clientId.Length == 0)
        {
            logger.LogWarning("A service account seed has no ClientId; it was skipped.");
            return;
        }

        var existing = await context.Principals.SingleOrDefaultAsync(p => p.LoginId == clientId, cancellationToken).ConfigureAwait(false);
        if (existing is not null)
        {
            await MatchTheGivenSecretAsync(existing, account.Secret, cancellationToken).ConfigureAwait(false);
            return;
        }

        if (string.IsNullOrWhiteSpace(account.Secret))
        {
            throw new InvalidOperationException($"The service account '{clientId}' needs a Secret in its Seed:ServiceAccounts entry.");
        }

        var client = new Principal(clientId, PrincipalType.ServiceAccount, account.DisplayName ?? clientId, null);
        client.AcceptInvitation(hasher.Hash(account.Secret), null);
        context.Principals.Add(client);
        await context.SaveChangesAsync(cancellationToken).ConfigureAwait(false);
        var assigned = await roleAssignments.AssignAsync(client.Id, account.Role, cancellationToken).ConfigureAwait(false);
        if (assigned.IsFailure)
        {
            throw new InvalidOperationException($"The role '{account.Role}' could not be assigned to '{clientId}': {assigned.Error.Message}.");
        }

        logger.LogInformation("Created the service account {ClientId} ({PrincipalId}) with the {Role} role.", clientId, client.Id, account.Role);
    }

    /// <summary>
    /// The fleet hands the seed the secret it keeps in the store. When the store lost it and the fleet made a new one,
    /// the account takes the new secret, so the store and the database agree again (ADR-0028); the change and its audit
    /// event are one transaction (ADR-0013). A secret the stored hash verifies changes nothing and writes nothing.
    /// </summary>
    private async Task MatchTheGivenSecretAsync(Principal existing, string? secret, CancellationToken cancellationToken)
    {
        if (existing.Type != PrincipalType.ServiceAccount)
        {
            logger.LogWarning("{LoginId} is a {Type}, not a service account; the seed leaves its credential alone.", existing.LoginId, existing.Type);
            return;
        }

        if (string.IsNullOrWhiteSpace(secret) || (existing.PasswordHash is not null && hasher.Verify(secret, existing.PasswordHash)))
        {
            logger.LogInformation("The service account {ClientId} exists already with this secret; nothing to seed.", existing.LoginId);
            return;
        }

        await using var transaction = await unitOfWork.BeginAsync(cancellationToken).ConfigureAwait(false);
        existing.SetPassword(hasher.Hash(secret));
        await context.SaveChangesAsync(cancellationToken).ConfigureAwait(false);
        await audit.WriteAsync(new AuditEvent(IdentityAuditEvents.ServiceAccountSecretChanged, AuditOutcome.Success, existing.Id, existing.LoginId, RecordType: "principal", RecordId: existing.Id, Reason: "seed"), cancellationToken).ConfigureAwait(false);
        await transaction.CommitAsync(cancellationToken).ConfigureAwait(false);
        logger.LogInformation("The service account {ClientId} ({PrincipalId}) had another secret; the seed set the one it was given.", existing.LoginId, existing.Id);
    }

    private async Task SeedAdministratorAsync(CancellationToken cancellationToken)
    {
        var loginId = Principal.NormaliseLoginId(options.LoginId);
        if (loginId.Length == 0)
        {
            logger.LogWarning("No first administrator is configured (Seed:Administrator:LoginId); none was created.");
            return;
        }

        var existing = await context.Principals.SingleOrDefaultAsync(p => p.LoginId == loginId, cancellationToken).ConfigureAwait(false);
        if (existing is not null)
        {
            if (existing.Status == PrincipalStatus.Invited)
            {
                // A seed that runs again (a provisioning step resumed) issues a fresh invitation; the earlier link is void.
                var fresh = await invitations.InviteAsync(existing, cancellationToken).ConfigureAwait(false);
                logger.LogInformation("The administrator {LoginId} ({PrincipalId}) is still Invited; a new invitation was issued. Invitation token: {Token}", loginId, existing.Id, fresh);
                return;
            }

            logger.LogInformation("The administrator {LoginId} exists already; nothing to seed.", loginId);
            return;
        }

        var administrator = new Principal(loginId, PrincipalType.User, options.DisplayName ?? "Administrator", loginId.Contains('@') ? loginId : null);
        context.Principals.Add(administrator);
        await context.SaveChangesAsync(cancellationToken).ConfigureAwait(false);

        var token = await invitations.InviteAsync(administrator, cancellationToken).ConfigureAwait(false);
        var assigned = await roleAssignments.AssignAsync(administrator.Id, SystemRoles.TenantAdministrator, cancellationToken).ConfigureAwait(false);
        if (assigned.IsFailure)
        {
            throw new InvalidOperationException($"The tenant-administrator role could not be assigned: {assigned.Error.Message}. Run the Authorization seeder first.");
        }

        logger.LogInformation("Created the first administrator {LoginId} ({PrincipalId}) in Invited status. Invitation token: {Token}", loginId, administrator.Id, token);
    }
}
